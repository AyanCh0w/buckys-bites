import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

// Editable SVGs are the source of truth. Native tabs need scale-aware images
// with a 28-point intrinsic size; their template mode applies the system tint.
const source = new URL("../app-icons/navigation/", import.meta.url);
const output = new URL("../assets/navigation/", import.meta.url);
const names = ["home", "menu", "nutrition", "ratings", "me"];
const webIcons = {};
await mkdir(output, { recursive: true });

for (const name of names) {
  const svg = await readFile(new URL(`${name}.svg`, source), "utf8");
  webIcons[name] = svg.trim();
  for (const selected of [false, true]) {
    const markup = selected
      ? svg.replace('stroke-width="1.8"', 'stroke-width="2.1"')
      : svg;
    for (const scale of [1, 2, 3]) {
      const suffix = `${selected ? "-selected" : ""}${scale === 1 ? "" : `@${scale}x`}`;
      await sharp(Buffer.from(markup), { density: 72 * scale })
        .resize(28 * scale, 28 * scale)
        .png()
        .toFile(fileURLToPath(new URL(`${name}${suffix}.png`, output)));
    }
  }
}

// Browsers use the same vector paths directly so even a 1x display stays sharp.
await writeFile(
  new URL("../src/lib/navigation-icons.web.ts", import.meta.url),
  `// Generated by scripts/generate-navigation-icons.mjs from app-icons/navigation/*.svg.\n` +
    `const source = (svg: string) => ({ uri: "data:image/svg+xml;utf8," + encodeURIComponent(svg) });\n` +
    `const states = (svg: string) => ({ default: source(svg), selected: source(svg.replace('stroke-width="1.8"', 'stroke-width="2.1"')) });\n` +
    `export const navigationIcons = {\n` +
    Object.entries(webIcons)
      .map(([name, svg]) => `  ${name}: states(${JSON.stringify(svg)}),`)
      .join("\n") +
    `\n} as const;\n`,
);

await writeFile(
  new URL("README.md", source),
  `# Navigation icons\n\nFive original line icons on a 28 × 28 grid, with rounded caps and joins. Default stroke: 1.8. Selected stroke: 2.1. Colors come from the app theme.\n\nEdit the SVG sources here, then run \`node scripts/generate-navigation-icons.mjs\` to regenerate the bundled PNG assets at 1×, 2×, and 3×.\n\nHome uses an arched doorway; Menu combines a plate, fork, and knife; Nutrition shows three chart segments; Ratings holds a star inside a speech bubble; Me is a circular profile.\n`,
);
console.log(
  "Generated five navigation icons, two states, three display scales.",
);
