import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
const groups = [ ['dishes','data/menu/scu-images/dishes',700], ['components','data/menu/scu-images/components',360], ['ratings','design/originals/bucky-ratings',180], ['cafes','design/originals/dining-icons',256] ];
const entries = [];
for (const [group, dir, size] of groups) {
  await fs.mkdir(`assets/${group}`,{recursive:true});
  for (const name of await fs.readdir(dir)) {
    if (!name.endsWith('.png')) continue;
    const extension = group === 'ratings' ? '.png' : '.webp';
    const target = `assets/${group}/${name.replace('.png', extension)}`;
    const image = sharp(path.join(dir,name)).resize(size,size,{fit:'inside',withoutEnlargement:true});
    await (group === 'ratings' ? image.png({ palette: true }) : image.webp({quality:86})).toFile(target);
    entries.push([`${group}/${name.replace('.png','')}`, target]);
  }
}
await fs.mkdir('assets/icons',{recursive:true});
for (const group of await fs.readdir('design/originals/app-icons')) {
  if (group.startsWith('.')) continue;
  for (const name of await fs.readdir(`design/originals/app-icons/${group}`)) {
    if (!name.endsWith('.png')) continue;
    const target=`assets/icons/${name.replace('.png','.webp')}`;
    await sharp(`design/originals/app-icons/${group}/${name}`).resize(256,256,{fit:'inside'}).webp({quality:88}).toFile(target);
    entries.push([`icons/${name.replace('.png','')}`,target]);
  }
}
// App icons come from composer-icon/buckysbites.icon; regenerate with npm run icons.
await fs.writeFile('src/data/assets.ts','// Generated by scripts/prepare-assets.mjs. Existing catalog art, bundled for offline use.\nexport const assets: Record<string, number> = {\n'+entries.map(([key,file])=>`  ${JSON.stringify(key)}: require('../../${file}'),`).join('\n')+'\n};\n');
console.log(`Prepared ${entries.length} optimized assets.`);
await import('./prepare-bakery-thumbnails.mjs');
