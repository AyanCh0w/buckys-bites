"""Compile dated Benson evidence into the ingestion configuration migration."""
from collections import defaultdict
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOTS = ROOT / 'data/menu/scu-catalog/snapshots'
OUTPUT = ROOT / 'supabase/migrations/20261119120100_benson_catalog_rules.sql'
NORMAL_WEEKDAYS = {'2026-11-17', '2026-11-18', '2026-11-19', '2026-11-20'}

# Only standing sections, supported by repeated placements before holiday hours.
# Prepared breakfast specials, weekly soups, and Sugar & Scoop stay date-bound.
STAPLE_STATIONS = {'18696', '18699', '22584', '24743', '18722', '18695', '26857'}
STAPLE_SECTIONS = {
    '18696': {'a la carte', 'chicken', 'salmon', 'simplyoasis plant-based', 'rice', 'rice bowl', 'fries', 'combo', 'dispenser', 'add-on', 'protein'},
    '18699': {'wraps', 'eggs', 'egg', 'tater tots', 'plant-based protein'},
    '22584': {'breakfast', 'meats'},
    '24743': {'entree', 'meats'},
    '18722': {'static', 'gluten free'},
    '18695': {'wrap'},
    '26857': {'bagels', 'breads', 'bread', 'breakfast bread', 'cereal', 'oatmeal', 'yogurt', 'waffles', 'pancakes'},
}


def snapshots(cafe):
    for path in sorted((SNAPSHOTS / cafe).glob('*.json')):
        yield json.loads(path.read_text())


def compact_item(item):
    keys = ('id', 'label', 'recipes', 'description', 'cor_icon', 'price', 'tier',
            'sizes', 'options', 'nutrition_details', 'ingredients', 'sub_station')
    return {key: item[key] for key in keys if key in item}


def observed_staples():
    candidates = defaultdict(dict)
    for cafe in ('marketplace-2', 'mission-bakery'):
        for menu in snapshots(cafe):
            day = menu['date']
            if day not in NORMAL_WEEKDAYS:
                continue
            for key, placements in menu['placements'].items():
                item = menu['items'][key]
                section = (item.get('sub_station') or '').lower()
                for placement in placements:
                    if cafe == 'mission-bakery':
                        if item.get('tier') != '2' or re.match(r'add\b', item['label'], re.I):
                            continue
                        station, period, shelf = cafe, 'All Day', placement['station']
                    else:
                        station, period, shelf = str(item['station_id']), placement['daypart'], None
                        if station not in STAPLE_STATIONS or section not in STAPLE_SECTIONS[station]:
                            continue
                        if station == '18696' and period != 'All Day 11-9:00':
                            continue
                        if item.get('tier') == '3' and not item.get('price'):
                            continue
                    # A different source ID or recipe is a different candidate.
                    candidates[station, period, shelf, key][day] = (item, menu['source'])
    result = []
    for (station, period, shelf, _), records in sorted(candidates.items()):
        if records.keys() != NORMAL_WEEKDAYS:
            continue
        item, url = records['2026-11-19']
        result.append(dict(station=station, period=period, section=shelf,
                           weekend=False, source=url, item=compact_item(item)))
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    mobile = json.loads((ROOT / 'scripts/benson-transact.json').read_text())
    holiday = json.loads((ROOT / 'scripts/benson-holiday-hours.json').read_text())
    rules = dict(holiday={key: holiday[key] for key in ('marketplace-2', 'mission-bakery')},
                 recurring=observed_staples())
    for name in ('trattoria', 'mission-bakery', 'pasta-groups'):
        rules[name] = mobile[name]
    sql = ['-- Generated by scripts/build-benson-catalog-rules.py from dated evidence.']
    for name, value in rules.items():
        payload = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
        assert '$evidence$' not in payload
        sql.append(f"insert into benson_private.catalog_rules(name,value) values ('{name}',$evidence${payload}$evidence$)\n"
                   'on conflict(name) do update set value=excluded.value;')
    content = '\n'.join(sql) + '\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Catalog rules migration does not match its evidence.')
    else:
        OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
